#!/usr/bin/env python3
"""String lints: a word is named once and reused (docs/NAMING.md N17).

A word-shaped literal (`"create"`, `"idle"`, `"widget_button"`) is a key or a
member of a closed set. Spelled twice, the spellings drift apart and nothing
says so. This reads shipped Rust and Balaur Script. Tests, generated files and
the constants themselves are left out.

  constant-respelled  a constant's value: one of this name in the file, an
                      engine constant, or a word with an underscore in it
  word-compared       one side of `==` or `!=`, or a match arm
  word-repeated       twice in one file, or three times in one package

Findings that predate the lint sit in a baseline, counted per file, so only a
new spelling fails. Every line in that file is debt.

  python3 scripts/string_lints.py [--fail-on-error] [--summary] [--debt]
  python3 scripts/string_lints.py --update-baseline
  python3 scripts/string_lints.py --project ../polyglot-pirates-app --summary
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from bisect import bisect_right
from collections import Counter, defaultdict
from dataclasses import dataclass
from pathlib import Path

BALAUR = Path(__file__).resolve().parent.parent
BASELINE_NAME = "string_lints_baseline.txt"
SKIP_DIRS = {"target", ".git", "node_modules", "build", "_build", "__pycache__", "tests", "benches"}
# Harnesses that drive the editor and record it: test scaffolding, in main's tree.
SCAFFOLD_SCRIPTS = {"selftest.bs", "showcase.bs"}
SKIP_CRATES = {"balaur_bench", "balaur_testkit"}
GENERATED = re.compile(r"written by clients/sdkgen|generated by|do not edit|@generated", re.I)

WORD = re.compile(r"[a-z][a-z0-9]*(?:[_-][a-z0-9]+)*")
FILE_REPEAT = 2
PACKAGE_REPEAT = 3

TOKEN = re.compile(
    r"//[^\n]*"
    r"|/\*.*?\*/"
    r'|(?<![\w])b?r(?P<hashes>#*)"(?P<raw>.*?)"(?P=hashes)'
    r'|(?<![\w])b?"(?P<text>(?:[^"\\]|\\.)*)"'
    r"|'(?:\\.[^'\n]*|[^\\'\n])'",
    re.S,
)
# A literal these hold is a message or a format, not a word of the program.
NON_WORD_CALL = re.compile(
    r"(?:\b(?:log::\w+|info|warn|error|debug|trace|println|eprintln|print|eprint|panic|bail"
    r"|anyhow|format|write|writeln|assert\w*|debug_assert\w*|unreachable|todo|unimplemented"
    r"|concat|include_str|include_bytes|env|option_env|stringify|cfg)!\s*\("
    r"|\.(?:expect|context|with_context)\(|\b(?:feature|target_\w+)\s*=)\s*$"
)
CONST_ITEM = re.compile(r"\b(?:const|static)\s+(?:mut\s+)?([A-Z][A-Z0-9_]*)\s*:[^=;]*=")
COMPARE_BEFORE = re.compile(r"[=!]=\s*$")
COMPARE_AFTER = re.compile(r"\s*(?:[=!]=|\)*\s*=>|\|(?!\|))")
# `"a" | "b"` closes on a word no `|` follows; a macro row is `name = "word" =>`.
PATTERN_BEFORE = re.compile(r"(?<!\|)\|\s*$")
ASSIGNED_BEFORE = re.compile(r"(?<![=!<>])=\s*$")
# A callback's value is the name of a method, which `fn` already spells.
# Quoted tokens and `toml!` take literals: a constant would not resolve or parse there.
QUOTED = re.compile(r"\b(?:(?:parse_)?quote(?:_spanned)?|toml|json)!\s*[({\[]")
CLOSERS = {"(": ")", "{": "}", "[": "]"}
CALLBACK_BEFORE = re.compile(r'\bon_\w+"?\s*:\s*$|\.call\(\s*$')
# What a reader sees is text, however much it looks like a word.
DISPLAY_BEFORE = re.compile(r'\b(?:text|label|title|tooltip|placeholder|help)"?\s*:\s*$')
KIND_FIELD_BEFORE = re.compile(r'\bkind"?\s*:\s*$')


@dataclass
class Site:
    path: Path
    line: int
    word: str
    compared: bool
    start: int
    end: int
    kind_field: bool = False


@dataclass
class Finding:
    path: Path
    line: int
    rule: str
    message: str


@dataclass
class Scan:
    sites: list[Site]
    constants: dict[str, str]


def masked_tokens(text: str, rust: bool) -> tuple[str, list[tuple[int, int, str]]]:
    """The source with strings and comments blanked, and each string's span."""
    out: list[str] = []
    strings: list[tuple[int, int, str]] = []
    last = 0
    for m in TOKEN.finditer(text):
        raw = m.group("raw")
        if raw is not None and not rust:
            continue
        out.append(text[last:m.start()])
        out.append(re.sub(r"[^\n]", " ", m.group(0)))
        last = m.end()
        value = raw if raw is not None else m.group("text")
        if value is not None and not m.group(0).startswith("b"):
            strings.append((m.start(), m.end(), value))
    out.append(text[last:])
    return "".join(out), strings


def closing(masked: str, start: int, opener: str, closer: str) -> int:
    depth = 0
    for i in range(start, len(masked)):
        if masked[i] == opener:
            depth += 1
        elif masked[i] == closer:
            depth -= 1
            if depth == 0:
                return i
    return len(masked)


def skipped_spans(masked: str, rust: bool) -> list[tuple[int, int]]:
    spans: list[tuple[int, int]] = []
    if rust:
        for m in re.finditer(r"#!?\[", masked):
            end = closing(masked, m.end() - 1, "[", "]")
            spans.append((m.start(), end))
            if re.match(r"#\[(?:cfg\(test\)|test|tokio::test)\]", masked[m.start():end + 1]):
                brace, semi = masked.find("{", end), masked.find(";", end)
                if brace >= 0 and not 0 <= semi < brace:
                    spans.append((m.start(), closing(masked, brace, "{", "}")))
        for m in re.finditer(r"macro_rules!\s+\w+\s*\{", masked):
            spans.append((m.start(), closing(masked, m.end() - 1, "{", "}")))
        own_macros = "|".join(re.findall(r"macro_rules!\s+(\w+)", masked))
        if own_macros:
            for m in re.finditer(rf"\b(?:{own_macros})!\s*[({{\[]", masked):
                opener = masked[m.end() - 1]
                spans.append((m.start(), closing(masked, m.end() - 1, opener, CLOSERS[opener])))
        for m in QUOTED.finditer(masked):
            spans.append((m.start(), closing(masked, m.end() - 1, masked[m.end() - 1], CLOSERS[masked[m.end() - 1]])))
    for m in CONST_ITEM.finditer(masked):
        end = masked.find(";", m.end())
        spans.append((m.start(), len(masked) if end < 0 else end))
    return sorted(spans)


def merged(spans: list[tuple[int, int]]) -> tuple[list[int], list[int]]:
    starts: list[int] = []
    ends: list[int] = []
    for a, b in sorted(spans):
        if ends and a <= ends[-1]:
            ends[-1] = max(ends[-1], b)
        else:
            starts.append(a)
            ends.append(b)
    return starts, ends


def inside(spans: tuple[list[int], list[int]], pos: int) -> bool:
    at = bisect_right(spans[0], pos) - 1
    return at >= 0 and pos <= spans[1][at]


def scan_file(path: Path) -> Scan | None:
    text = path.read_text(errors="ignore")
    if GENERATED.search(text[:400]):
        return None
    rust = path.suffix == ".rs"
    masked, strings = masked_tokens(text, rust)
    spans = merged(skipped_spans(masked, rust))
    newlines = [i for i, c in enumerate(text) if c == "\n"]
    constants: dict[str, str] = {}
    for m in CONST_ITEM.finditer(masked):
        for a, _, value in strings:
            if m.end() <= a <= m.end() + 8 and WORD.fullmatch(value):
                constants[value] = m.group(1)
    sites: list[Site] = []
    if path.name != "vocabulary.rs":
        for start, end, value in strings:
            if len(value) < 2 or not WORD.fullmatch(value) or inside(spans, start):
                continue
            before = masked[max(0, start - 48):start]
            raw_before = text[max(0, start - 48):start]
            if (NON_WORD_CALL.search(before) or CALLBACK_BEFORE.search(raw_before)
                    or DISPLAY_BEFORE.search(raw_before)):
                continue
            compared = bool(
                COMPARE_BEFORE.search(before)
                or (rust and PATTERN_BEFORE.search(before))
                or (COMPARE_AFTER.match(masked, end) and not ASSIGNED_BEFORE.search(before)))
            sites.append(Site(path, bisect_right(newlines, start) + 1, value, compared, start, end,
                              bool(KIND_FIELD_BEFORE.search(raw_before))))
    return Scan(sites, constants)


def bs_package(rel: Path, root: Path) -> str:
    parts = rel.parts
    for marker in ("addons", "deps"):
        if marker in parts[:-1]:
            at = parts.index(marker)
            return "/".join(parts[:at + 2])
    for parent in (root / rel).parents:
        if (parent / "project.toml").exists():
            return str(parent.relative_to(root)) or "."
        if parent == root:
            break
    return parts[0] if len(parts) > 1 else "."


def tree_files(root: Path) -> list[Path]:
    """Asks git, whose index answers in milliseconds; a walk stats every asset."""
    listed = subprocess.run(
        ["git", "ls-files", "-co", "--exclude-standard", "--", "*.rs", "*.bs"],
        cwd=root, capture_output=True, text=True, check=False)
    if listed.returncode == 0:
        return [Path(line) for line in listed.stdout.splitlines()]
    return [p.relative_to(root) for p in root.rglob("*") if p.suffix in (".rs", ".bs")]


def source_files(root: Path, is_engine: bool) -> list[tuple[Path, str]]:
    found: list[tuple[Path, str]] = []
    for rel in tree_files(root):
        folders = rel.parts[:-1]
        if SKIP_DIRS.intersection(folders) or rel.name.startswith("test_") or rel.name in SCAFFOLD_SCRIPTS:
            continue
        if is_engine and folders[:1] not in (("crates",), ("editor",), ("examples",)):
            continue
        if not is_engine and "addons" in folders:
            continue
        if not (root / rel).is_file():
            continue
        if rel.suffix == ".bs":
            found.append((root / rel, bs_package(rel, root)))
        elif is_engine and shipped_rust(rel):
            found.append((root / rel, rel.parts[1]))
    return found


def shipped_rust(rel: Path) -> bool:
    parts = rel.parts
    return (len(parts) > 3 and parts[0] == "crates" and parts[2] == "src"
            and parts[1] not in SKIP_CRATES
            and rel.name != "tests.rs" and not rel.name.endswith("_tests.rs"))


def engine_constants() -> tuple[dict[str, str], dict[str, str]]:
    """The engine's words: those specific enough to match anywhere, and the widget kinds."""
    api = BALAUR / "docs" / "generated" / "api.json"
    if not api.exists():
        return {}, {}
    named: dict[str, str] = {}
    widgets: dict[str, str] = {}
    modules = json.loads(api.read_text())["modules"]
    for module in modules.values() if isinstance(modules, dict) else modules:
        for constant in module.get("constants") or []:
            value = str(constant.get("value", "")).strip('"')
            if not WORD.fullmatch(value):
                continue
            path = f"{module.get('name', '')}::{constant['name']}"
            if constant["name"].startswith("WIDGET_"):
                widgets.setdefault(value, path)
            if "_" in value:
                named.setdefault(value, path)
    return named, widgets


def fits(name: str, word: str) -> bool:
    """Whether a constant is this word and not another that spells the same."""
    return name == word.upper().replace("-", "_") or "_" in word


def constant_for(site: Site, in_file: dict[str, str], in_package: dict[str, str],
                 engine: dict[str, str], widgets: dict[str, str]) -> str | None:
    script = site.path.suffix == ".bs"
    if script and site.kind_field and site.word in widgets:
        return widgets[site.word]
    if script and site.word in engine:
        return engine[site.word]
    here = in_file.get(site.word)
    if here and fits(here, site.word):
        return here
    return in_package.get(site.word) if "_" in site.word else None


def findings_for(root: Path, files: list[tuple[Path, str]]) -> tuple[list[Finding], dict[str, Counter]]:
    by_package: dict[str, list[Site]] = defaultdict(list)
    constants: dict[str, dict[str, str]] = defaultdict(dict)
    file_constants: dict[Path, dict[str, str]] = {}
    for path, package in files:
        scanned = scan_file(path)
        if scanned:
            by_package[package].extend(scanned.sites)
            constants[package].update(scanned.constants)
            file_constants[path] = scanned.constants
    engine, widgets = engine_constants()
    findings: list[Finding] = []
    words: dict[str, Counter] = {}
    for package, sites in by_package.items():
        total = Counter(s.word for s in sites)
        in_file = Counter((s.path, s.word) for s in sites)
        words[package] = total
        for s in sites:
            rel = s.path.relative_to(root)
            named = constant_for(s, file_constants[s.path], constants[package], engine, widgets)
            if named:
                findings.append(Finding(rel, s.line, "constant-respelled", f'"{s.word}" equals {named}; use it, or name this one'))
            elif s.compared:
                findings.append(Finding(rel, s.line, "word-compared", f'"{s.word}" compared; name it as a constant'))
            elif in_file[(s.path, s.word)] >= FILE_REPEAT or total[s.word] >= PACKAGE_REPEAT:
                findings.append(Finding(rel, s.line, "word-repeated",
                                        f'"{s.word}" spelled {total[s.word]} times in {package}; name it once'))
    findings.sort(key=lambda f: (str(f.path), f.line))
    return findings, words


def read_baseline(path: Path) -> Counter:
    counts: Counter = Counter()
    if path.exists():
        for line in path.read_text().splitlines():
            if line and not line.startswith("#"):
                file, rule, n = line.split("\t")
                counts[f"{file}\t{rule}"] = int(n)
    return counts


def write_baseline(path: Path, counts: Counter) -> None:
    path.write_text(
        "# Word literals that predate the lint. Never add to this file by hand;\n"
        "# regenerate with: python3 scripts/string_lints.py --update-baseline\n"
        "# Every line here is debt. Deleting one is progress.\n"
        + "".join(f"{k}\t{v}\n" for k, v in sorted(counts.items())))


def print_summary(findings: list[Finding], words: dict[str, Counter], root: Path,
                  files: list[tuple[Path, str]]) -> None:
    by_package: dict[str, Counter] = defaultdict(Counter)
    packages = {str(p.relative_to(root)): pkg for p, pkg in files}
    for f in findings:
        by_package[packages.get(str(f.path), "?")][f.rule] += 1
    print("findings  respelled  compared  repeated  package  (top words)")
    for package, rules in sorted(by_package.items(), key=lambda kv: -sum(kv[1].values())):
        top = " ".join(f"{w}:{c}" for w, c in words[package].most_common(6))
        print(f"{sum(rules.values()):8d}  {rules['constant-respelled']:9d}  {rules['word-compared']:8d}"
              f"  {rules['word-repeated']:8d}  {package}  ({top})")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--project", type=Path, help="lint a Balaur project's own scripts instead of the engine")
    ap.add_argument("--fail-on-error", action="store_true")
    ap.add_argument("--summary", action="store_true", help="findings per package, and its most-spelled words")
    ap.add_argument("--update-baseline", action="store_true", help="record current findings as the accepted debt")
    ap.add_argument("--debt", action="store_true", help="print the outstanding debt and exit")
    args = ap.parse_args()

    is_engine = args.project is None
    root = BALAUR if is_engine else args.project.resolve()
    baseline = (BALAUR / "scripts" if is_engine else root) / BASELINE_NAME
    files = source_files(root, is_engine)
    findings, words = findings_for(root, files)
    counts = Counter(f"{f.path}\t{f.rule}" for f in findings)

    if args.update_baseline:
        write_baseline(baseline, counts)
        print(f"baseline written: {sum(counts.values())} findings across {len(counts)} entries")
        return 0
    base = read_baseline(baseline)
    if args.debt:
        print(f"outstanding debt: {sum(base.values())} findings across {len(base)} file/rule pairs")
        for key, n in base.most_common():
            file, rule = key.split("\t")
            print(f"  {n:5d}  {rule:20s} {file}")
        return 0
    if args.summary:
        print_summary(findings, words, root, files)

    seen: Counter = Counter()
    new: list[Finding] = []
    for f in findings:
        key = f"{f.path}\t{f.rule}"
        seen[key] += 1
        if seen[key] > base[key]:
            new.append(f)
    for f in new:
        print(f"ERROR  {f.path}:{f.line}  [{f.rule}] {f.message}")
    print(f"\n{len(new)} new findings · {sum(base.values())} accepted (debt: --debt)")
    return 1 if (new and args.fail_on_error) else 0


if __name__ == "__main__":
    sys.exit(main())
