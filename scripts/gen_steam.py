def int_shape(t: T, model: Model) -> tuple[int, bool] | None:
    """Bits and signedness of an integer type, or None."""
    r = t.resolved(model)
    if r.kind == "enum":
        return 32, True
    if r.kind == "prim" and PRIMS[r.name][3] == "int":
        rust = PRIMS[r.name][0]
        return (64 if rust == "isize" else int(rust[1:])), rust.startswith("i")
    return None


def eval_const(expr: str, known: dict) -> int | float:
    e = re.sub(r"(?i)\b(0x[0-9a-f]+|\d+)u?ll?\b", r"\1", expr)
    e = re.sub(r"(\d)U\b", r"\1", e)
    e = re.sub(r"(\d+)\.f\b", r"\1.0", e)
    e = re.sub(r"'(.)'", lambda m: str(ord(m.group(1))), e)
    e = re.sub(r"\(\s*[A-Za-z_][A-Za-z0-9_]*\s*\)\s*(?=[~(\d])", "", e)
    e = re.sub(r"\b[A-Za-z_][A-Za-z0-9_]*", lambda m: repr(known[m.group(0)]), e)
    return eval(e, {"__builtins__": {}})  # noqa: S307 - constant arithmetic from Valve's json


def rust_literal(value, t: T, model: Model) -> str:
    if isinstance(value, float):
        return repr(value)
    shape = int_shape(t, model)
    if shape is None:
        return repr(value)
    bits, signed = shape
    value %= 1 << bits
    if signed and value >= 1 << (bits - 1):
        value -= 1 << bits
    return str(value)


def scalar_kind(t: T, model: Model) -> str | None:
    """The script type of a value a script passes or gets as one number or flag."""
    r = t.resolved(model)
    if r.kind == "enum" or r.kind in ("steamid", "gameid"):
        return "int"
    if r.kind == "prim" and PRIMS[r.name][3] in ("int", "float", "bool"):
        return PRIMS[r.name][3]
    return None


def struct_attrs(model: Model, name: str) -> list[str]:
    if name in model.opaque:
        return ["#[repr(C)]"]
    if name in PACK_1:
        return [f"/// Packed to 1, as `{PACK_1[name]}` declares it.", "#[repr(C, packed)]"]
    if name in NATURAL:
        return [f"/// Natural alignment, as `{NATURAL[name]}` declares it.", "#[repr(C)]"]
    return ["/// Valve's callback packing: 8 on Windows, 4 on Linux and macOS.",
            '#[cfg_attr(target_os = "windows", repr(C, packed(8)))]',
            '#[cfg_attr(not(target_os = "windows"), repr(C, packed(4)))]']


def field_ident(name: str) -> str:
    return f"r#{name}" if name in RUST_KEYWORDS else name


def emit_types(d: dict, model: Model) -> str:
    out = [BANNER, "//! Steamworks SDK " + SDK_VERSION + "'s types, as `steam_api.json` describes them.\n",
           ALLOWS, "\nuse std::ffi::{c_char, c_void};\n",
           "\n/// A type every bit pattern of zeroes is a valid value of: what Steam reads and writes.",
           "///\n/// # Safety\n/// Only for plain C data: integers, floats, `bool`, pointers and arrays of them.",
           "pub unsafe trait Plain: Copy {}\n",
           "/// A value of zeroes, the start of every out parameter.",
           "pub fn zeroed<T: Plain>() -> T {",
           "    // SAFETY: `Plain` promises zeroes are a value.",
           "    unsafe { std::mem::zeroed() }", "}\n"]
    for prim in ("bool", "i8", "u8", "i16", "u16", "i32", "u32", "i64", "u64", "isize", "f32", "f64"):
        out.append(f"unsafe impl Plain for {prim} {{}}")
    out.append("unsafe impl<T: Plain, const N: usize> Plain for [T; N] {}")
    out.append("unsafe impl<T> Plain for *mut T {}\nunsafe impl<T> Plain for *const T {}\n")
    out.append("/// Valve's flat spelling of a `CSteamID` and a `CGameID` passed by value.")
    out.append("pub type uint64_steamid = u64;\npub type uint64_gameid = u64;\n")
    out.append("/// A Steam id as a struct holds it: `steamclientpublic.h` packs the class to 1.")
    out.append("#[repr(C, packed)]\n#[derive(Clone, Copy)]\npub struct CSteamID(pub u64);\n")
    out.append("/// A game id as a struct holds it, packed to 1 as `CSteamID` is.")
    out.append("#[repr(C, packed)]\n#[derive(Clone, Copy)]\npub struct CGameID(pub u64);\n")
    out.append("unsafe impl Plain for CSteamID {}\nunsafe impl Plain for CGameID {}\n")
    for t in d["typedefs"]:
        out.append(f"pub type {t['typedef']} = {model.rust(model.typedefs[t['typedef']])};")
    out.append("")
    known: dict = {}
    for name, values in model.enums.items():
        out.append(f"/// `{name}`.\npub type {name} = i32;")
