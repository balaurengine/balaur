def snake(name: str) -> str:
    """Valve's PascalCase as a Rust or script name: `GetSteamID` is `get_steam_id`."""
    for whole, spelled in (("IPv6", "Ipv6"), ("IPv4", "Ipv4"), ("IDs", "Ids"), ("URLs", "Urls"),
                           ("UGCs", "Ugcs"), ("DLCs", "Dlcs")):
        name = name.replace(whole, spelled)
    name = re.sub(r"(?<=[A-Z])(?=[A-Z][a-z])", "_", name)
    name = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    return re.sub(r"_+", "_", name).lower().strip("_")


def method_name(name: str) -> str:
    """A method's script name: Valve's `B` before a bool reader is its type,
    not a word, so `BIsSubscribed` is `is_subscribed`."""
    if re.match(r"B[A-Z][a-z]", name):
        name = name[1:]
    return snake(name)


def value_name(name: str) -> str:
    """A field or parameter without Valve's `m_` and type prefix:
    `m_ulSteamIDLobby` is `steam_id_lobby`, `pchName` is `name`."""
    name = re.sub(r"^m_", "", name)
    m = re.match(r"^([a-z][a-z0-9]*)(?=[A-Z])", name)
    if m and m.group(1) in HUNGARIAN:
        name = name[len(m.group(1)):]
    return snake(name)


def distinct_names(raw: list[str]) -> list[str]:
    """`value_name` of each, or the whole name where two would meet."""
    stripped = [value_name(n) for n in raw]
    counts = {n: stripped.count(n) for n in stripped}
    return [snake(re.sub(r"^m_", "", r)) if counts[s] > 1 or s in RESERVED or not s else s
            for r, s in zip(raw, stripped)]


def record_name(struct: str) -> str:
    return re.sub(r"_t$", "", struct)


@dataclass
class T:
    """A C type: `kind` is prim, typedef, enum, struct, steamid, gameid, ptr,
    array, fnptr, iface, void or unknown."""
    kind: str
    name: str = ""
    inner: "T | None" = None
    const: bool = False
    ref: bool = False
    count: int = 0

    def resolved(self, model: "Model") -> "T":
        t = self
        while t.kind == "typedef":
            t = model.typedefs[t.name]
        return t


@dataclass
class Model:
    typedefs: dict[str, T] = field(default_factory=dict)
    enums: dict[str, list[tuple[str, int]]] = field(default_factory=dict)
    structs: dict[str, dict] = field(default_factory=dict)
    callbacks: dict[str, int] = field(default_factory=dict)
    layouts: dict = field(default_factory=dict)
    opaque: dict[str, str] = field(default_factory=dict)
    unchecked: set[str] = field(default_factory=set)

    def parse(self, ctype: str) -> T:
        s = ctype.strip()
        if "(*)" in s:
            return T("fnptr", name=s)
        if s.endswith("&"):
            inner = self.parse(s[:-1])
            if inner.kind == "array":
                return T("ptr", inner=inner, const=s.startswith("const"), ref=True)
            return T("ptr", inner=inner, const=s.startswith("const"), ref=True)
        m = re.fullmatch(r"(.*?)\s*\[(\d+)\]", s)
        if m:
            return T("array", inner=self.parse(m.group(1)), count=int(m.group(2)))
        if s.endswith("*"):
            base = s[:-1].strip()
            const = base.startswith("const ") and not base.endswith("*")
            return T("ptr", inner=self.parse(base), const=const)
        s = re.sub(r"^(const|struct|class)\s+", "", s).strip()
        s = re.sub(r"\s+const$", "", s)
        if "::" in s:
            outer, inner = s.split("::", 1)
            if inner in self.enums:
                return T("enum", name=inner)
            return T("unknown", name=s)
        if s == "void":
            return T("void")
        if s in PRIMS:
            return T("prim", name=s)
        if s in self.typedefs:
            return T("typedef", name=s)
        if s in self.enums:
            return T("enum", name=s)
        if s in self.structs:
            return T("struct", name=s)
        if s == "CSteamID":
            return T("steamid")
        if s == "CGameID":
            return T("gameid")
        if s.startswith("ISteam"):
            return T("iface", name=s)
        return T("unknown", name=s)

    def rust(self, t: T) -> str:
        """The type as the generated Rust spells it."""
        if t.kind == "prim":
            return PRIMS[t.name][0]
        if t.kind in ("typedef", "enum", "struct"):
            return t.name
        if t.kind == "steamid":
            return "CSteamID"
        if t.kind == "gameid":
            return "CGameID"
        if t.kind == "void":
            return "c_void"
        if t.kind == "iface" or t.kind == "unknown":
            return "c_void"
        if t.kind == "array":
            return f"[{self.rust(t.inner)}; {t.count}]"
        if t.kind == "fnptr":
            return self.fnptr(t.name)
        if t.kind == "ptr":
            inner = t.inner
            mut = "const" if t.const else "mut"
            return f"*{mut} {self.rust(inner)}"
        raise ValueError(t)

    def fnptr(self, spelled: str) -> str:
        m = re.fullmatch(r"(.*?)\s*\(\*\)\s*\((.*)\)", spelled)
        ret, args = m.group(1), m.group(2)
        parts = [a.strip() for a in args.split(",") if a.strip() and a.strip() != "void"]
        rendered = ", ".join(self.rust(self.parse(p)) for p in parts)
        r = self.parse(ret)
        tail = "" if r.kind == "void" else f" -> {self.rust(r)}"
        return f"Option<unsafe extern \"C\" fn({rendered}){tail}>"

    def size_align(self, t: T, platform: str) -> tuple[int, int]:
        t = t.resolved(self)
        if t.kind == "prim":
            _, size, align, _ = PRIMS[t.name]
            return size, align
        if t.kind == "enum":
            return 4, 4
        if t.kind in ("steamid", "gameid"):
            # Both are classes in steamclientpublic.h's pack(1) region.
            return 8, 1
        if t.kind in ("ptr", "fnptr"):
            return 8, 8
        if t.kind == "array":
            size, align = self.size_align(t.inner, platform)
            return size * t.count, align
        if t.kind == "struct":
            got = self.layout_of(t.name, platform)
            return got["size"], got["align"]
        raise ValueError(f"no size for {t}")

    def pack(self, struct: str, platform: str) -> int | None:
        if struct in PACK_1:
            return 1
        if struct in NATURAL:
            return None
        return 8 if platform == "windows" else 4

    def layout_of(self, struct: str, platform: str) -> dict:
        if struct in self.opaque:
            return self.layouts[platform][struct]
        pack = self.pack(struct, platform)
        offset, biggest, offsets = 0, 1, {}
        for f in self.structs[struct]["fields"]:
            size, align = self.size_align(self.parse(f["fieldtype"]), platform)
            if pack:
                align = min(align, pack)
            offset = -(-offset // align) * align
            offsets[f["fieldname"]] = offset
            offset += size
            biggest = max(biggest, align)
        if not self.structs[struct]["fields"]:
            offset = 1
        return {"size": -(-offset // biggest) * biggest, "align": biggest, "offsets": offsets}

    def mappable_struct(self, name: str) -> str | None:
        """Why `name` cannot be a script record, or None when it can."""
        if name in self.opaque:
            return f"`{name}` is {self.opaque[name]}"
        if name in self.unchecked:
            return f"`{name}` has no recorded layout to check its packing against"
        for f in self.structs[name]["fields"]:
            why = self.field_unmappable(self.parse(f["fieldtype"]))
            if why:
                return f"`{name}.{f['fieldname']}` is {why}"
        return None

    def field_unmappable(self, t: T) -> str | None:
        r = t.resolved(self)
        if r.kind in ("prim", "enum", "steamid", "gameid"):
            return None
        if r.kind == "array":
            inner = r.inner.resolved(self)
            if inner.kind == "struct":
                return self.mappable_struct(inner.name)
            return self.field_unmappable(inner)
        if r.kind == "struct":
            return self.mappable_struct(r.name)
        if r.kind == "ptr" and is_c_string(r, self):
            return None
        if r.kind in ("ptr", "fnptr"):
            # A pointer field is left out of the record, never read.
            return None
        return f"a `{r.kind}`"


def is_c_string(t: T, model: Model) -> bool:
    if t.kind != "ptr":
        return False
    inner = t.inner.resolved(model)
    return inner.kind == "prim" and inner.name == "char"


def load_model() -> tuple[dict, Model]:
    d = json.loads((SDK / "steam_api.json").read_text())
    model = Model()
    model.layouts = json.loads((SDK / "layouts.json").read_text())
    for e in d["enums"]:
        model.enums[e["enumname"]] = [(v["name"], int(v["value"])) for v in e["values"]]
    for owner in d["interfaces"] + d["structs"] + d["callback_structs"]:
        for e in owner.get("enums", []):
            model.enums[e["enumname"]] = [(v["name"], int(v["value"])) for v in e["values"]]
    for s in d["structs"] + d["callback_structs"] + EXTRA_STRUCTS:
        model.structs[s["struct"]] = s
    for s in d["callback_structs"]:
        model.callbacks[s["struct"]] = s["callback_id"]
    # Typedefs after the names they may point at are known.
    for t in d["typedefs"]:
        model.typedefs[t["typedef"]] = None
    for t in d["typedefs"]:
        model.typedefs[t["typedef"]] = model.parse(t["type"])
    model.opaque = dict(OPAQUE)
    return d, model


def read_layouts(sys_dir: Path, names: set[str]) -> dict:
    """Each struct's size, alignment and offsets as steamworks-sys's bindgen
    tests record them, per platform."""
    out = {}
    for platform, file in BINDINGS.items():
        text = (sys_dir / "src" / file).read_text()
        found = {}
        for m in re.finditer(r"fn bindgen_test_layout_(\w+)\(\) \{(.*?)\n\}\n", text, re.S):
            name, body = m.group(1), m.group(2)
            if name not in names:
                continue
            size = re.search(r"size_of::<\w+>\(\),\s*(\d+)usize", body)
            align = re.search(r"align_of::<\w+>\(\),\s*(\d+)usize", body)
            offsets = {f: int(o) for f, o in re.findall(
                r"addr_of!\(\(\*ptr\)\.(\w+)\) as usize - ptr as usize \},\s*(\d+)usize", body)}
            found[name] = {"size": int(size.group(1)), "align": int(align.group(1)),
                           "offsets": offsets}
        out[platform] = dict(sorted(found.items()))
    return out


def check_layouts(model: Model) -> list[str]:
    """Where the packing rule and the recorded layout disagree."""
    wrong = []
    for name in model.structs:
        for platform in PLATFORMS:
            want = model.layouts[platform].get(name)
            if want is None:
                model.unchecked.add(name)
                continue
            if name in model.opaque:
                continue
            got = model.layout_of(name, platform)
            if (got["size"], got["align"]) != (want["size"], want["align"]):
                wrong.append(f"{name} on {platform}: {got['size']}/{got['align']}, "
                             f"recorded {want['size']}/{want['align']}")
                continue
            for f, off in want["offsets"].items():
                if got["offsets"].get(f, off) != off:
                    wrong.append(f"{name}.{f} on {platform}: at {got['offsets'][f]}, recorded {off}")
    return wrong


